#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const OUTPUTS = {
    css: resolve(root, 'static_site/src/styles/tokens.css'),
    swift: resolve(root, 'mobile/Arc Agent/Arc Agent/Theme/DesignTokens.swift'),
    js: resolve(root, 'static_site/src/styles/palette.js'),
};

const HEADER = 'Generated by design/build-tokens.mjs from design/tokens.json. Do not edit.';

export const loadTokens = () => JSON.parse(readFileSync(resolve(root, 'design/tokens.json'), 'utf8'));

export const resolveColor = (tokens, ref) => {
    const [family, step] = ref.split('.');
    const value = tokens.primitive[family]?.[step];
    if (!value) throw new Error(`Unknown primitive color ${ref}`);
    return value;
};

export const semanticColors = (tokens, mode) => {
    const index = mode === 'dark' ? 1 : 0;
    return Object.fromEntries(
        Object.entries(tokens.semantic).map(([name, refs]) => [name, resolveColor(tokens, refs[index])])
    );
};

const channel = (value) => {
    const c = value / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
};

const luminance = (hex) => {
    const n = parseInt(hex.slice(1), 16);
    return 0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255);
};

export const contrastRatio = (a, b) => {
    const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
    return (hi + 0.05) / (lo + 0.05);
};

const cssName = (name) => name.replace('/', '-');
const bezier = (points) => `cubic-bezier(${points.join(', ')})`;

const cssColorBlock = (colors, indent) =>
    Object.entries(colors).map(([name, hex]) => `${indent}--color-${cssName(name)}: ${hex};`);

const cssShadowBlock = (tokens, index, indent) =>
    Object.entries(tokens.shadow).map(([name, values]) => `${indent}--shadow-${name}: ${values[index]};`);

export const buildCss = (tokens) => {
    const light = semanticColors(tokens, 'light');
    const dark = semanticColors(tokens, 'dark');
    const lines = [`/* ${HEADER} */`, '', ':root {', '    color-scheme: light dark;'];

    lines.push(`    --font-sans: '${tokens.font.sans}', ui-sans-serif, system-ui, -apple-system, 'Segoe UI', sans-serif;`);
    lines.push(`    --font-mono: '${tokens.font.mono}', ui-monospace, 'SF Mono', Menlo, monospace;`);
    for (const [name, t] of Object.entries(tokens.typography)) {
        lines.push(
            `    --text-${name}-size: ${t.size / 16}rem;`,
            `    --text-${name}-line: ${+(t.line / t.size).toFixed(4)};`,
            `    --text-${name}-weight: ${t.weight};`,
            `    --text-${name}-tracking: ${t.tracking}em;`
        );
    }
    for (const [name, value] of Object.entries(tokens.space)) lines.push(`    --space-${name}: ${value}px;`);
    for (const [name, value] of Object.entries(tokens.radius)) lines.push(`    --radius-${name}: ${value}px;`);
    for (const [name, value] of Object.entries(tokens.motion.duration)) lines.push(`    --duration-${name}: ${value}ms;`);
    for (const [name, value] of Object.entries(tokens.motion.easing)) lines.push(`    --ease-${name}: ${bezier(value)};`);
    for (const [name, value] of Object.entries(tokens.layout)) lines.push(`    --layout-${name}: ${value}px;`);
    lines.push(...cssColorBlock(light, '    '), ...cssShadowBlock(tokens, 0, '    '), '}', '');

    const darkBody = [...cssColorBlock(dark, '        '), ...cssShadowBlock(tokens, 1, '        ')];
    lines.push(
        '@media (prefers-color-scheme: dark) {',
        '    :root:not([data-theme="light"]) {',
        ...darkBody,
        '    }',
        '}',
        '',
        ':root[data-theme="light"] {',
        '    color-scheme: light;',
        '}',
        '',
        ':root[data-theme="dark"] {',
        '    color-scheme: dark;',
        ...darkBody.map((line) => line.slice(4)),
        '}',
        '',
        '@media (prefers-reduced-motion: reduce) {',
        '    :root {',
        ...Object.keys(tokens.motion.duration).map((name) => `        --duration-${name}: 0.01ms;`),
        '    }',
        '}',
        ''
    );
    return lines.join('\n');
};

export const buildJs = (tokens) =>
    [
        `// ${HEADER}`,
        `export const palette = ${JSON.stringify(tokens.primitive, null, 4)};`,
        '',
    ].join('\n');

const swiftName = (name) =>
    name
        .split(/[/-]/)
        .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
        .join('');

const swiftHex = (hex) => `0x${hex.slice(1).toUpperCase()}`;

export const buildSwift = (tokens) => {
    const light = semanticColors(tokens, 'light');
    const dark = semanticColors(tokens, 'dark');
    const lines = [
        `// ${HEADER}`,
        'import SwiftUI',
        'import UIKit',
        '',
        'enum DesignTokens {',
        '    enum Palette {',
        ...Object.keys(light).map(
            (name) => `        static let ${swiftName(name)} = Color(light: ${swiftHex(light[name])}, dark: ${swiftHex(dark[name])})`
        ),
        '    }',
        '',
        '    enum Space {',
        ...Object.entries(tokens.space).map(([name, value]) => `        static let s${name}: CGFloat = ${value}`),
        '    }',
        '',
        '    enum Radius {',
        ...Object.entries(tokens.radius).map(([name, value]) => `        static let ${name}: CGFloat = ${value}`),
        '    }',
        '',
        '    enum Duration {',
        ...Object.entries(tokens.motion.duration).map(([name, value]) => `        static let ${name}: Double = ${value / 1000}`),
        '    }',
        '',
        '    enum Layout {',
        ...Object.entries(tokens.layout).map(([name, value]) => `        static let ${swiftName(name)}: CGFloat = ${value}`),
        '    }',
        '}',
        '',
        'extension Color {',
        '    init(light: UInt32, dark: UInt32) {',
        '        self.init(uiColor: UIColor { traits in',
        '            let hex = traits.userInterfaceStyle == .dark ? dark : light',
        '            return UIColor(',
        '                red: CGFloat((hex >> 16) & 0xFF) / 255,',
        '                green: CGFloat((hex >> 8) & 0xFF) / 255,',
        '                blue: CGFloat(hex & 0xFF) / 255,',
        '                alpha: 1',
        '            )',
        '        })',
        '    }',
        '}',
        '',
    ];
    return lines.join('\n');
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const tokens = loadTokens();
    writeFileSync(OUTPUTS.css, buildCss(tokens));
    writeFileSync(OUTPUTS.swift, buildSwift(tokens));
    writeFileSync(OUTPUTS.js, buildJs(tokens));
    console.log(Object.values(OUTPUTS).map((path) => `Wrote ${path}`).join('\n'));
}
